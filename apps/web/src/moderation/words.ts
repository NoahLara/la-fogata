/**
 * What La Fogata does not take, in Spanish and English: insults, swearing, slurs, threats and wishing harm.
 * Written as people write them, with accents and capitals not mattering; `fold.ts` makes every spelling the
 * same before comparing, and words of eight letters or more also match with one letter wrong.
 *
 * - `WORDS_*`: a whole word. One ending in `*` also matches the word with up to three more letters
 *   ("mierd*" is mierda, mierdas, mierdoso); one ending in `**` with up to eight more (diminutives and the
 *   like: "cerot**" is cerotillo). Use `**` only for stems nobody uses for anything else.
 * - `PHRASES`: said as a run of letters with no spaces, so they are found however they are spaced or joined
 *   ("hijo de puta", "hijodeputa", "h i j o d e p u t a"). Keep them long (8 letters or more, or a word nobody
 *   uses otherwise, like "cerote") so they are never found by chance across two ordinary words.
 * - `ROOTS`: pieces found inside any single word, for roots no ordinary word contains.
 * - `MASKED`: words with a letter hidden behind a star or a dot ("p*ta").
 * - `ALLOWED`: ordinary words, names and places that look like a bad one, written as they are.
 *
 * It leaves out what is also an ordinary word (cage, witch, hostia, perra, gorda, inútil, tonto) because a
 * wrongly refused word is felt by someone who came here to be heard. "cono" is not here either: see the check
 * for "coño" in `content.ts`.
 */

